%% Example 3 - Surface roughness and volumetric defects combined
% Surface valleys: peaks over threshold, exceedances of Rv above u are
% exponential (GP, zero shape); V exceedances per mm of surface.
% Y_R is the shielding factor of the roughness with K = Y_R s sqrt(pi Rv).

mat = flpm.material('Ti64-AB');
YR  = flpm.roughnessShielding(0.020, 0.160);          % Rv, RSm in mm

u = 0.020;
rough = flpm.defectPopulation('surface', ...
    'Size', makedist('Exponential', 'mu', 0.010), 'SizeOffset', u, ...
    'CountPerLength', 0.35, 'ShieldingFactor', YR, 'Name', 'AB surface');
pores = flpm.defectPopulation('volumetric', ...
    'Size',  makedist('Lognormal', 'mu', log(0.060), 'sigma', 0.20), ...
    'Depth', makedist('Gamma', 'a', 2.0, 'b', 0.12), ...
    'CountPerLength', 0.5, 'Name', 'pores');

T = flpm.monteCarlo({pores, rough}, mat, 'SurfaceLength', pi*7.3, ...
    'NumSimulations', 200, 'Seed', 3, 'UseParallel', true);
fprintf('Median dSigma_w = %.0f MPa; %.0f %% of failures from the surface\n', ...
    median(T.stress), 100*mean(T.killerPopulation == 2));
